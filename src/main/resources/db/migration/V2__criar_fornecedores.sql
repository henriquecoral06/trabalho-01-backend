-- Cria a tabela de fornecedores: as empresas que entregam mercadoria no centro de distribuição.
CREATE TABLE fornecedores (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Guarda o nome obrigatório do fornecedor.
    nome VARCHAR(255) NOT NULL,
    -- Guarda o CNPJ obrigatório; com a pontuação, ele tem 18 caracteres.
    cnpj VARCHAR(18) NOT NULL
);
