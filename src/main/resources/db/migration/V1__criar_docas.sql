-- Cria a tabela de docas: os portões onde os caminhões encostam para descarregar.
-- Só guarda os dados. As regras de negócio (R1, R2 e R3) ficam no AgendamentoService.
CREATE TABLE docas (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Guarda como a doca é chamada no pátio, por exemplo D-01.
    identificacao VARCHAR(20) NOT NULL,
    -- Diz se a doca tem câmara fria para receber carga refrigerada.
    refrigerada BOOLEAN NOT NULL
);
