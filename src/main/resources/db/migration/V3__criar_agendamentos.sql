-- Cria a tabela de agendamentos: cada linha reserva uma doca, num horário,
-- para a descarga de um fornecedor. Vem depois de V1 e V2 porque referencia as duas tabelas.
-- Não tem CHECK, UNIQUE nem trigger: as regras R1, R2 e R3 ficam no AgendamentoService.
CREATE TABLE agendamentos (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Quem vai entregar. REFERENCES cria a chave estrangeira: o PostgreSQL
    -- recusa um fornecedor_id que não exista em fornecedores(id).
    fornecedor_id BIGINT NOT NULL REFERENCES fornecedores (id),
    -- Em qual doca o caminhão vai descarregar, com a mesma garantia em docas(id).
    doca_id BIGINT NOT NULL REFERENCES docas (id),
    -- Dia e hora em que a doca começa a ficar reservada.
    inicio TIMESTAMP NOT NULL,
    -- Dia e hora em que a doca fica livre de novo.
    fim TIMESTAMP NOT NULL,
    -- Diz se a carga precisa de câmara fria.
    carga_refrigerada BOOLEAN NOT NULL
);
